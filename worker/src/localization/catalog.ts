export const SUPPORTED_LOCALES = Object.keys(catalogs);
export const DEFAULT_LOCALE = "en-US";
export type LocaleKey = keyof typeof catalogs["en-US"];
export type LocaleVariables = Record<string, string | number>;

export function resolveLocale(locale?: string, guildLocale?: string): string {
  for (const candidate of [locale, guildLocale]) {
    if (candidate?.toLowerCase() === "en-gb") return DEFAULT_LOCALE;
    const exact = SUPPORTED_LOCALES.find(value => value.toLowerCase() === candidate?.toLowerCase());
    if (exact) return exact;
  }
  return DEFAULT_LOCALE;
}

export function translate(key: LocaleKey, locale = DEFAULT_LOCALE, variables: LocaleVariables = {}): string {
  const catalog = catalogs[resolveLocale(locale) as keyof typeof catalogs];
  return catalog[key].replace(/\{([A-Za-z]\w*)\}/g, (match, name: string) => {
    const value = variables[name];
    return value === undefined ? match : String(value);
  });
}

export function localizations(key: LocaleKey): Record<string, string> {
  return Object.fromEntries(SUPPORTED_LOCALES.filter(locale => locale !== DEFAULT_LOCALE).map(locale => [locale, translate(key, locale)]));
}
